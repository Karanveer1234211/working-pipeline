def _agg_block(df: pd.DataFrame) -> pd.Series:
    n = len(df)
    if n == 0:
        return pd.Series({"n": 0})
    return pd.Series({
        "n": n,
        "win_rate_pct": (df["return_pct"] > 0).mean() * 100,
        "avg_ret_pct": df["return_pct"].mean(),
        "median_ret_pct": df["return_pct"].median(),
        "std_pct": df["return_pct"].std(),
        "avg_net_pct": df["net_return_pct"].mean(),
        "sharpe_per_trade": (df["return_pct"].mean() / df["return_pct"].std()
                              if df["return_pct"].std() > 0 else np.nan),
        "tp_rate_pct": (df["exit_reason"] == "tp").mean() * 100,
        "sl_rate_pct": (df["exit_reason"] == "sl").mean() * 100,
        "time_rate_pct": (df["exit_reason"] == "time").mean() * 100,
        "avg_bars_held": df["bars_held"].mean(),
        "avg_mae_pct": df["mae_pct"].mean(),
        "avg_mfe_pct": df["mfe_pct"].mean(),
        "p10_ret": df["return_pct"].quantile(0.10),
        "p90_ret": df["return_pct"].quantile(0.90),
    })


def write_summaries(df: pd.DataFrame, funnel_df: pd.DataFrame, watchlist: pd.DataFrame):
    # 02 funnel: how many signals -> entries per variant
    sig_count = len(watchlist)
    funnel_summary = (funnel_df.groupby("variant")
                      .size().rename("n_entries").reset_index())
    funnel_summary["n_signals"] = sig_count
    funnel_summary["entry_rate_pct"] = (funnel_summary["n_entries"] / sig_count * 100).round(2)
    # days-to-break percentiles per variant
    dtb = (funnel_df.groupby("variant")["days_to_break"]
           .agg(["mean", "median", "max"]).reset_index()
           .rename(columns={"mean": "days_to_break_avg",
                            "median": "days_to_break_median",
                            "max": "days_to_break_max"}))
    funnel_summary = funnel_summary.merge(dtb, on="variant", how="left")
    funnel_summary.to_csv(OUT_DIR / "02_signal_funnel.csv", index=False)
    print(f"[Out] 02_signal_funnel.csv -> {len(funnel_summary)} variants")

    # 03 by variant (use the "no SL, no TP" cells -- pure ORB hold)
    pure = df[(df["sl_opt"] == "None") & (df["tp_opt"] == "None")]
    by_var = pure.groupby("variant").apply(_agg_block).reset_index()
    by_var.to_csv(OUT_DIR / "03_summary_by_variant.csv", index=False)
    print(f"[Out] 03_summary_by_variant.csv -> {len(by_var)} variants")

    # 04 by variant x regime
    by_vr = pure.groupby(["variant", "regime"]).apply(_agg_block).reset_index()
    by_vr.to_csv(OUT_DIR / "04_by_variant_regime.csv", index=False)
    print(f"[Out] 04_by_variant_regime.csv -> {len(by_vr)} cells")

    # 05 by variant x prob bucket
    by_vb = pure.groupby(["variant", "prob_bucket"]).apply(_agg_block).reset_index()
    by_vb.to_csv(OUT_DIR / "05_by_variant_bucket.csv", index=False)
    print(f"[Out] 05_by_variant_bucket.csv -> {len(by_vb)} cells")

    # 06 SL x TP grid per variant
    for variant in df["variant"].unique():
        sub = df[df["variant"] == variant]
        grid = sub.groupby(["sl_opt", "tp_opt"]).apply(_agg_block).reset_index()
        grid.to_csv(OUT_DIR / f"06_sl_tp_grid_{variant}.csv", index=False)
        print(f"[Out] 06_sl_tp_grid_{variant}.csv -> {len(grid)} cells")

    # 07 MAE/MFE distribution per variant (use full-hold path, dedupe per entry)
    if not funnel_df.empty:
        rows = []
        for variant in funnel_df["variant"].unique():
            sub = funnel_df[funnel_df["variant"] == variant]
            for q in (0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95):
                rows.append({
                    "variant": variant, "quantile": q,
                    "mae_pct_q": sub["mae_full_pct"].quantile(q),
                    "mfe_pct_q": sub["mfe_full_pct"].quantile(q),
                })
        pd.DataFrame(rows).to_csv(OUT_DIR / "07_mae_mfe_distribution.csv", index=False)
        print(f"[Out] 07_mae_mfe_distribution.csv")

    # 08 holding time distribution
    rows = []
    for variant in pure["variant"].unique():
        sub = pure[pure["variant"] == variant]
        for q in (0.10, 0.25, 0.50, 0.75, 0.90):
            rows.append({
                "variant": variant, "quantile": q,
                "bars_held_q": sub["bars_held"].quantile(q),
                "approx_days": sub["bars_held"].quantile(q) / BARS_PER_DAY,
            })
    pd.DataFrame(rows).to_csv(OUT_DIR / "08_holding_time_dist.csv", index=False)
    print(f"[Out] 08_holding_time_dist.csv")


