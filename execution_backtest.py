def run_backtest():
    t0 = time.perf_counter()
    watchlist = load_watchlist()
    if watchlist.empty:
        print("[ERROR] Empty watchlist; nothing to backtest.")
        return None

    rows = []
    funnel = []
    cost_pct = ROUND_TRIP_BPS / 100.0  # e.g. 25 bps -> 0.25%

    n_signals = len(watchlist)
    for s_idx, sig in watchlist.iterrows():
        T = pd.Timestamp(sig["date"]).tz_localize(None) if pd.Timestamp(sig["date"]).tz is None \
            else pd.Timestamp(sig["date"]).tz_convert("Asia/Kolkata").tz_localize(None)
        symbol = sig["symbol"]
        prob = float(sig["prob"])
        regime = sig["regime"]

        if (s_idx + 1) % 500 == 0:
            print(f"[Backtest] {s_idx+1:,}/{n_signals:,} signals processed "
                  f"(elapsed {time.perf_counter()-t0:.0f}s)")

        for variant in ORB_VARIANTS:
            broken = False
            for d_off in range(1, MAX_WATCH_DAYS + 1):
                wd = T + pd.Timedelta(days=d_off)
                if wd.weekday() >= 5:
                    continue
                bars = load_intraday_5min(symbol, wd)
                if bars is None or len(bars) < (variant["window_min"] // 5) + 1:
                    continue

                lvl = compute_orb_levels(bars, variant["window_min"])
                if lvl is None:
                    continue
                orb_high, orb_low, last_orb_idx = lvl

                brk = find_orb_break(bars, orb_high, orb_low, last_orb_idx + 1, variant)
                if brk is None:
                    continue

                # ENTRY at break-bar close
                entry_price = brk["close"]
                entry_idx = brk["idx"]
                # Bars AFTER entry (entry bar excluded -- realistic: stop/target test starts next bar)
                post_bars = collect_post_entry_bars(symbol, wd, entry_idx + 1, MAX_HOLD_BARS)
                if post_bars is None or len(post_bars) == 0:
                    continue

                # MAE/MFE on FULL hold path (no SL/TP) -- diagnostic
                lows_min = float(post_bars["low"].min())
                highs_max = float(post_bars["high"].max())
                mae_full = (lows_min / entry_price - 1) * 100
                mfe_full = (highs_max / entry_price - 1) * 100

                funnel.append({
                    "variant": variant["name"], "symbol": symbol, "signal_date": T,
                    "entry_date": wd, "days_to_break": d_off,
                    "orb_high": orb_high, "orb_low": orb_low,
                    "entry_price": entry_price,
                    "mae_full_pct": mae_full, "mfe_full_pct": mfe_full,
                    "prob": prob, "regime": regime,
                    "prob_bucket": bucket_label(prob),
                })

                # Exit grid: every (sl, tp) combination
                for sl_opt in SL_OPTIONS:
                    sl_price = compute_sl_price(entry_price, sl_opt, orb_low)
                    for tp_opt in TP_OPTIONS:
                        tp_price = entry_price * (1 + float(tp_opt) / 100.0) if tp_opt is not None else None
                        ex = derive_exit(entry_price, post_bars, sl_price, tp_price)
                        rows.append({
                            "symbol": symbol, "signal_date": T,
                            "entry_date": wd, "days_to_break": d_off,
                            "variant": variant["name"],
                            "orb_high": orb_high, "orb_low": orb_low,
                            "entry_price": entry_price,
                            "sl_opt": str(sl_opt), "tp_opt": str(tp_opt) if tp_opt is not None else "None",
                            "sl_price": sl_price, "tp_price": tp_price,
                            "exit_price": ex["exit_price"],
                            "exit_reason": ex["exit_reason"],
                            "bars_held": ex["bars_held"],
                            "return_pct": ex["return_pct"],
                            "net_return_pct": ex["return_pct"] - cost_pct,
                            "mae_pct": ex["mae_pct"],
                            "mfe_pct": ex["mfe_pct"],
                            "mae_full_pct": mae_full,
                            "mfe_full_pct": mfe_full,
                            "prob": prob, "regime": regime,
                            "prob_bucket": bucket_label(prob),
                        })
                broken = True
                break  # this variant got its break -- next variant
            # End of watch-day loop. If broken==False, no entry recorded for this variant.

    df = pd.DataFrame(rows)
    funnel_df = pd.DataFrame(funnel)
    elapsed = time.perf_counter() - t0
    print(f"[Backtest] Done in {elapsed:.0f}s. Total trade-rows: {len(df):,}  "
          f"unique entries: {len(funnel_df):,}")
    return df, funnel_df, watchlist


