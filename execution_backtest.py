def bucket_label(p: float) -> str:
    for lo, hi in PROB_BUCKETS:
        if lo <= p < hi:
            return f"[{lo:.2f}, {hi:.2f})"
    return "out_of_range"


def safe_div(a, b):
    return a / b if b not in (0, None) and not (isinstance(b, float) and np.isnan(b)) else np.nan


def _model_predict_proba(model, X: pd.DataFrame) -> np.ndarray:
    if hasattr(model, "predict_proba"):
        return model.predict_proba(X)[:, 1]
    if hasattr(model, "members") and model.members:
        ps = [m.predict_proba(X)[:, 1] for m in model.members]
        return np.mean(ps, axis=0)
    raise RuntimeError("Cannot score with this model object.")


def load_watchlist() -> pd.DataFrame:
    """Score panel with the live model. Return rows with prob >= PROB_THRESHOLD,
    restricted to the OOS slice (last WATCHLIST_OOS_FRACTION of dates).
    Columns: symbol, date, prob, regime."""
    print(f"[Load] Panel: {PANEL_PATH}")
    panel = pd.read_parquet(PANEL_PATH)
    panel["timestamp"] = pd.to_datetime(panel["timestamp"])
    if panel["timestamp"].dt.tz is not None:
        panel["timestamp"] = panel["timestamp"].dt.tz_convert("Asia/Kolkata")
    panel["date"] = panel["timestamp"].dt.normalize()

    # Universe filter
    panel["avg20_vol"] = panel.groupby("symbol")["volume"].transform(
        lambda s: s.rolling(20, min_periods=1).mean())
    universe = (panel["close"] >= MIN_CLOSE) & (panel["avg20_vol"] >= MIN_AVG20_VOL)
    panel = panel[universe].reset_index(drop=True)

    # OOS slice
    all_dates = np.sort(panel["date"].unique())
    cut_idx = int(len(all_dates) * (1 - WATCHLIST_OOS_FRACTION))
    test_start = pd.Timestamp(all_dates[cut_idx])
    print(f"[Load] OOS test window: {test_start.date()} to {pd.Timestamp(all_dates[-1]).date()}")
    panel_test = panel[panel["date"] >= test_start].copy()

    # Schema + model
    schema = json.loads(SCHEMA_PATH.read_text())
    feats = list(schema["features"])
    impute = {k: float(v) for k, v in schema["impute"].items()}
    X = panel_test.reindex(columns=feats).copy()
    for c in feats:
        X[c] = pd.to_numeric(X[c], errors="coerce").fillna(impute.get(c, 0.0))

    if USE_REGIME_ROUTER and ROUTER_FILE.exists():
        print(f"[Load] Router: {ROUTER_FILE}")
        router = load(ROUTER_FILE)
        regime_vec = panel_test["stock_regime"].fillna("bull_trend").reset_index(drop=True)
        prob = router.predict_proba_by_regime(X.reset_index(drop=True), regime_vec)
    else:
        print(f"[Load] Pooled model: {MODEL_FILE}")
        model = load(MODEL_FILE)
        prob = _model_predict_proba(model, X)

    panel_test["prob"] = prob
    wl = panel_test[panel_test["prob"] >= PROB_THRESHOLD].copy()
    wl["regime"] = wl.get("stock_regime", "unknown").fillna("unknown")
    wl = wl[["symbol", "date", "prob", "regime"]].reset_index(drop=True)
    print(f"[Watchlist] {len(wl):,} signals at prob >= {PROB_THRESHOLD} "
          f"(out of {len(panel_test):,} panel rows in OOS window)")
    return wl


def load_intraday_5min(symbol: str, day: pd.Timestamp) -> Optional[pd.DataFrame]:
    """Load 5-min bars for symbol on `day` (one trading day).
    Returns DataFrame[timestamp(IST tz-aware), open, high, low, close, volume]
    sorted ascending. Returns None if file missing / empty / no bars on this day."""
    day_norm = day.normalize().tz_localize(None) if hasattr(day, "tz_localize") and day.tz is None else day.normalize()
    if hasattr(day_norm, "tz") and day_norm.tz is not None:
        day_norm = day_norm.tz_localize(None)

    if INTRADAY_LAYOUT == "per_symbol":
        path = INTRADAY_DIR / f"{symbol}_5min.parquet"
        if not path.exists():
            # try without _5min suffix
            alt = INTRADAY_DIR / f"{symbol}.parquet"
            if alt.exists():
                path = alt
            else:
                return None
        try:
            df = pd.read_parquet(path)
        except Exception:
            return None
    elif INTRADAY_LAYOUT == "per_symbol_date":
        path = INTRADAY_DIR / symbol / f"{day_norm.strftime('%Y-%m-%d')}.parquet"
        if not path.exists():
            return None
        try:
            df = pd.read_parquet(path)
        except Exception:
            return None
    else:
        raise ValueError(f"Unknown INTRADAY_LAYOUT: {INTRADAY_LAYOUT}")

    if df is None or df.empty:
        return None

    # Normalize columns
    cmap = {c.lower(): c for c in df.columns}
    ts_col = cmap.get("timestamp") or cmap.get("date") or cmap.get("datetime")
    if ts_col is None:
        return None
    df["timestamp"] = pd.to_datetime(df[ts_col])
    if df["timestamp"].dt.tz is None:
        df["timestamp"] = df["timestamp"].dt.tz_localize("Asia/Kolkata", nonexistent="shift_forward",
                                                         ambiguous="NaT")
    else:
        df["timestamp"] = df["timestamp"].dt.tz_convert("Asia/Kolkata")
    df = df.dropna(subset=["timestamp"]).sort_values("timestamp").reset_index(drop=True)

    # Lowercase OHLCV
    for src, dst in (("Open", "open"), ("High", "high"), ("Low", "low"),
                     ("Close", "close"), ("Volume", "volume")):
        if src in df.columns and dst not in df.columns:
            df[dst] = df[src]
    needed = ["timestamp", "open", "high", "low", "close", "volume"]
    if not all(c in df.columns for c in needed):
        return None
    df = df[needed].copy()
    for c in ("open", "high", "low", "close", "volume"):
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df.dropna(subset=["open", "high", "low", "close"]).reset_index(drop=True)

    # Slice to the requested day (IST date)
    same_day = df["timestamp"].dt.normalize() == pd.Timestamp(day_norm).tz_localize("Asia/Kolkata")
    df_day = df.loc[same_day].reset_index(drop=True)
    if df_day.empty:
        return None
    return df_day


def compute_orb_levels(bars: pd.DataFrame, window_min: int) -> Optional[Tuple[float, float, int]]:
    """Compute opening-range high/low over the first `window_min` minutes.
    Returns (orb_high, orb_low, last_orb_bar_idx) or None."""
    n_bars = max(1, window_min // 5)
    if len(bars) < n_bars + 1:
        return None
    orb_slice = bars.iloc[:n_bars]
    orb_high = float(orb_slice["high"].max())
    orb_low  = float(orb_slice["low"].min())
    last_idx = n_bars - 1
    return orb_high, orb_low, last_idx


def find_orb_break(bars: pd.DataFrame, orb_high: float, orb_low: float,
                   start_idx: int, variant: dict) -> Optional[Dict]:
    """Find the first 5-min bar (idx >= start_idx) whose CLOSE > orb_high
    AND any variant-specific filter passes.
    Returns {idx, time, close, vwap_at_break, vol_at_break} or None."""
    if start_idx >= len(bars):
        return None

    # Pre-compute session VWAP up to each bar (cumulative typical-price-weighted)
    typical = (bars["high"] + bars["low"] + bars["close"]) / 3.0
    cum_pv = (typical * bars["volume"]).cumsum()
    cum_v  = bars["volume"].cumsum().replace(0, np.nan)
    vwap_series = cum_pv / cum_v

    n_orb_bars = (start_idx + 1)
    orb_avg_vol = bars.iloc[:n_orb_bars]["volume"].mean() if n_orb_bars > 0 else 0.0

    for i in range(start_idx, len(bars)):
        row = bars.iloc[i]
        close = float(row["close"])
        if close <= orb_high:
            continue

        # Filters
        ok = True
        for f in variant.get("filters", []):
            if f == "vwap":
                vwap_now = float(vwap_series.iloc[i]) if pd.notna(vwap_series.iloc[i]) else None
                if vwap_now is None or close <= vwap_now:
                    ok = False
                    break
            elif f == "vol_1p5x":
                vol_now = float(row["volume"])
                if orb_avg_vol == 0 or vol_now < 1.5 * orb_avg_vol:
                    ok = False
                    break
        if not ok:
            continue

        return {
            "idx": int(i),
            "time": row["timestamp"],
            "close": close,
            "vwap_at_break": float(vwap_series.iloc[i]) if pd.notna(vwap_series.iloc[i]) else np.nan,
            "vol_at_break": float(row["volume"]),
        }
    return None


def collect_post_entry_bars(symbol: str, entry_day: pd.Timestamp, entry_idx_in_day: int,
                            max_bars: int) -> Optional[pd.DataFrame]:
    """Concatenate 5-min bars from entry_idx_in_day on entry_day forward,
    spanning subsequent trading days, up to max_bars bars."""
    out = []
    same_day = load_intraday_5min(symbol, entry_day)
    if same_day is None:
        return None
    out.append(same_day.iloc[entry_idx_in_day:].reset_index(drop=True))

    days_forward = 1
    while sum(len(x) for x in out) < max_bars and days_forward <= MAX_HOLD_DAYS + 7:
        next_day = entry_day + pd.Timedelta(days=days_forward)
        days_forward += 1
        # Skip weekends
        if next_day.weekday() >= 5:
            continue
        nxt = load_intraday_5min(symbol, next_day)
        if nxt is None:
            continue  # holiday / missing
        out.append(nxt)

    if not out:
        return None
    full = pd.concat(out, ignore_index=True).reset_index(drop=True)
    return full.iloc[:max_bars].reset_index(drop=True)


def derive_exit(entry_price: float, post_bars: pd.DataFrame,
                sl_price: Optional[float], tp_price: Optional[float]) -> Dict:
    """Walk forward through post_bars (excluding the entry bar itself if you've
    already sliced; here post_bars[0] is the bar AFTER entry). Apply gap-aware
    stop-before-target logic. If neither hits, time-stop at last bar's close.

    Returns dict: exit_price, exit_reason, bars_held, return_pct, mae_pct, mfe_pct.
    """
    if post_bars is None or len(post_bars) == 0:
        return {
            "exit_price": entry_price, "exit_reason": "no_data",
            "bars_held": 0, "return_pct": 0.0, "mae_pct": 0.0, "mfe_pct": 0.0,
        }

    mae_low  = entry_price
    mfe_high = entry_price

    for i, row in enumerate(post_bars.itertuples(index=False)):
        bar_open  = float(row.open)
        bar_high  = float(row.high)
        bar_low   = float(row.low)
        bar_close = float(row.close)

        mae_low  = min(mae_low, bar_low)
        mfe_high = max(mfe_high, bar_high)

        # SL FIRST (gap-down: if open <= sl, fill at open; else fill at sl)
        if sl_price is not None and bar_low <= sl_price:
            fill = bar_open if bar_open <= sl_price else sl_price
            return {
                "exit_price": fill, "exit_reason": "sl",
                "bars_held": i + 1,
                "return_pct": (fill / entry_price - 1) * 100,
                "mae_pct": (mae_low / entry_price - 1) * 100,
                "mfe_pct": (mfe_high / entry_price - 1) * 100,
            }

        # TP SECOND (gap-up: if open >= tp, fill at open; else at tp)
        if tp_price is not None and bar_high >= tp_price:
            fill = bar_open if bar_open >= tp_price else tp_price
            return {
                "exit_price": fill, "exit_reason": "tp",
                "bars_held": i + 1,
                "return_pct": (fill / entry_price - 1) * 100,
                "mae_pct": (mae_low / entry_price - 1) * 100,
                "mfe_pct": (mfe_high / entry_price - 1) * 100,
            }

    # Time stop at last bar close
    last_close = float(post_bars.iloc[-1]["close"])
    return {
        "exit_price": last_close, "exit_reason": "time",
        "bars_held": len(post_bars),
        "return_pct": (last_close / entry_price - 1) * 100,
        "mae_pct": (mae_low / entry_price - 1) * 100,
        "mfe_pct": (mfe_high / entry_price - 1) * 100,
    }


def compute_sl_price(entry_price: float, sl_opt, orb_low: float) -> Optional[float]:
    if sl_opt is None:
        return None
    if isinstance(sl_opt, str) and sl_opt == "orb_low":
        return orb_low
    return entry_price * (1 - float(sl_opt) / 100.0)


