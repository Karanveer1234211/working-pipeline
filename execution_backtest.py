#!/usr/bin/env python3
"""
=============================================================================
EXECUTION BACKTEST  (prob >= 0.65 watchlist + ORB trigger + SL/TP grid)
=============================================================================

WHAT THIS DOES
--------------
For each watchlist signal (model prob >= PROB_THRESHOLD on day T):
  1. Wait T+1..T+MAX_WATCH_DAYS for the first ORB break (multiple variants).
  2. On break, ENTER at the break-bar 5-min close.
  3. Simulate exit under every (SL, TP) combination from entry forward.
  4. Track MAE/MFE on the full hold path (not just to exit).

ORB VARIANTS (free to add more in ORB_VARIANTS):
  ORB_15m       : 5-min close > first-15-min HIGH
  ORB_30m       : 5-min close > first-30-min HIGH
  ORB_60m       : 5-min close > first-60-min HIGH
  ORB_15m_vwap  : ORB_15m AND break-bar close > session VWAP
  ORB_15m_vol   : ORB_15m AND break-bar volume > 1.5x first-15-min avg volume

EXIT GRID (per trade we compute every combination):
  SL: None, -2%, -3%, -5%, orb_low
  TP: None, +2%, +3%, +5%

GAP-AWARE STOPS:
  At each post-entry bar:
    - SL check first (if low <= SL: fill at min(open, SL); handles gap-down)
    - TP check second (if high >= TP: fill at max(open, TP); handles gap-up)
    - If neither: continue
  After MAX_HOLD_BARS bars (~5 trading days): time-stop at last close.

OUTPUTS (in OUT_DIR):
  01_per_trade.csv             every (signal x variant x SL x TP) row
  02_signal_funnel.csv         watchlist -> break -> entry counts per variant
  03_summary_by_variant.csv    headline stats per ORB variant
  04_by_variant_regime.csv     ORB x regime
  05_by_variant_bucket.csv     ORB x prob bucket
  06_sl_tp_grid_<variant>.csv  full SL x TP heatmap (one per variant)
  07_mae_mfe_distribution.csv  per-variant MAE/MFE percentiles
  08_holding_time_dist.csv     bars-held distribution per variant

ASSUMPTIONS
-----------
* 5-min intraday bars cached as `<symbol>_5min.parquet` per symbol (or per
  symbol+date — set INTRADAY_LAYOUT). Adjust load_intraday_5min() if your
  cache layout differs.
* NSE 9:15-15:30 = 75 5-min bars/day. Holidays skipped automatically by
  joining on actual bar timestamps.
* Watchlist is generated by scoring panel_cache.parquet with the live model
  (m5_ensemble.joblib by default; override via MODEL_FILE).
* Cost: 25 bps round-trip applied to net returns columns.

Run:  python execution_backtest.py
=============================================================================
"""

